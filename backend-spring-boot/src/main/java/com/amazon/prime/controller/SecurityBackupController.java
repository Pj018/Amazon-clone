package com.amazon.prime.controller;

import com.amazon.prime.entity.BackupSnapshot;
import com.amazon.prime.entity.SecurityAuditLog;
import com.amazon.prime.service.SecurityBackupService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import lombok.RequiredArgsConstructor;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.util.List;
import java.util.Map;

@RestController
@RequestMapping("/api/v1/security")
@RequiredArgsConstructor
@CrossOrigin(origins = "*")
@Tag(name = "Security Vault & Backup API", description = "Endpoints for encrypted snapshot backups, SHA-256 integrity, and audit logs")
public class SecurityBackupController {

    private final SecurityBackupService securityBackupService;

    @GetMapping("/backups")
    @Operation(summary = "List all encrypted database snapshots")
    public ResponseEntity<List<BackupSnapshot>> getBackups() {
        return ResponseEntity.ok(securityBackupService.getAllBackups());
    }

    @PostMapping("/backups/trigger")
    @Operation(summary = "Trigger on-demand automated backup")
    public ResponseEntity<BackupSnapshot> triggerBackup(@RequestBody(required = false) Map<String, Boolean> payload) {
        boolean isAuto = payload != null && Boolean.TRUE.equals(payload.get("autoGenerated"));
        BackupSnapshot snapshot = securityBackupService.triggerBackup(isAuto);
        return ResponseEntity.status(HttpStatus.CREATED).body(snapshot);
    }

    @GetMapping("/audit-logs")
    @Operation(summary = "Retrieve real-time security event audit trails")
    public ResponseEntity<List<SecurityAuditLog>> getAuditLogs() {
        return ResponseEntity.ok(securityBackupService.getAuditLogs());
    }
}
