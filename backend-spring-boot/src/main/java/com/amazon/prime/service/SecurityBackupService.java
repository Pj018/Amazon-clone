package com.amazon.prime.service;

import com.amazon.prime.entity.BackupSnapshot;
import com.amazon.prime.entity.SecurityAuditLog;
import com.amazon.prime.repository.BackupSnapshotRepository;
import com.amazon.prime.repository.OrderRepository;
import com.amazon.prime.repository.ProductRepository;
import com.amazon.prime.repository.SecurityAuditLogRepository;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.security.MessageDigest;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.Base64;
import java.util.List;
import java.util.UUID;

@Service
@RequiredArgsConstructor
@Transactional(readOnly = true)
public class SecurityBackupService {

    private final BackupSnapshotRepository backupRepository;
    private final SecurityAuditLogRepository auditLogRepository;
    private final OrderRepository orderRepository;
    private final ProductRepository productRepository;

    public List<BackupSnapshot> getAllBackups() {
        return backupRepository.findAllByOrderByCreatedAtDesc();
    }

    public List<SecurityAuditLog> getAuditLogs() {
        return auditLogRepository.findTop50ByOrderByCreatedAtDesc();
    }

    @Transactional
    public BackupSnapshot triggerBackup(boolean isAuto) {
        long orderCount = orderRepository.count();
        long productCount = productRepository.count();

        String timestamp = LocalDateTime.now().format(DateTimeFormatter.ofPattern("MMM dd, yyyy HH:mm:ss"));
        String rawData = "PRIME-BACKUP-ORDERS:" + orderCount + "-PROD:" + productCount + "-TIME:" + System.currentTimeMillis();
        String checksum = calculateSha256(rawData);
        String encryptedPayload = Base64.getEncoder().encodeToString(rawData.getBytes());

        BackupSnapshot snapshot = BackupSnapshot.builder()
                .id("bck-" + UUID.randomUUID().toString().substring(0, 8))
                .timestamp(timestamp)
                .version("v3.4." + (int)(Math.random() * 50))
                .ordersCount((int) orderCount)
                .productsCount((int) productCount)
                .checksum(checksum)
                .encryptedPayload("ENC_AES256GCM_" + encryptedPayload)
                .autoGenerated(isAuto)
                .build();

        BackupSnapshot saved = backupRepository.save(snapshot);

        // Record audit trail
        logSecurityEvent("AUTOMATED_ENCRYPTED_BACKUP_COMPLETED", "127.0.0.1", "SpringBoot-Daemon", "SUCCESS");

        return saved;
    }

    @Transactional
    public SecurityAuditLog logSecurityEvent(String event, String ip, String device, String status) {
        String timestamp = LocalDateTime.now().format(DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss"));
        String signature = "SIG_" + calculateSha256(event + timestamp + ip).substring(0, 16).toUpperCase();

        SecurityAuditLog log = SecurityAuditLog.builder()
                .id("audit-" + UUID.randomUUID().toString().substring(0, 8))
                .event(event)
                .timestamp(timestamp)
                .ipAddress(ip)
                .device(device)
                .status(status)
                .signature(signature)
                .build();

        return auditLogRepository.save(log);
    }

    private String calculateSha256(String base) {
        try {
            MessageDigest digest = MessageDigest.getInstance("SHA-256");
            byte[] hash = digest.digest(base.getBytes("UTF-8"));
            StringBuilder hexString = new StringBuilder();
            for (byte b : hash) {
                String hex = Integer.toHexString(0xff & b);
                if (hex.length() == 1) hexString.append('0');
                hexString.append(hex);
            }
            return hexString.toString();
        } catch (Exception ex) {
            return UUID.randomUUID().toString().replace("-", "");
        }
    }
}
