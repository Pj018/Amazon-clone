export interface Product {
  id: string;
  title: string;
  brand: string;
  category: 'electronics' | 'fashion' | 'home' | 'books' | 'beauty' | 'audio';
  price: number;
  originalPrice: number;
  rating: number;
  reviewCount: number;
  image: string;
  additionalImages?: string[];
  isPrime: boolean;
  isBestSeller?: boolean;
  inStock: boolean;
  stockCount: number;
  description: string;
  features: string[];
  specs: Record<string, string>;
  colors?: string[];
  sizes?: string[];
}

export interface CartItem {
  product: Product;
  quantity: number;
  selectedColor?: string;
  selectedSize?: string;
}

export interface OrderItem {
  productId: string;
  title: string;
  price: number;
  quantity: number;
  image: string;
  selectedColor?: string;
}

export interface Order {
  id: string;
  date: string;
  status: 'Processing' | 'Shipped' | 'Out for Delivery' | 'Delivered' | 'Returned';
  items: OrderItem[];
  total: number;
  shippingAddress: Address;
  deliveryOption: 'prime_one_day' | 'standard' | 'priority_overnight';
  trackingNumber: string;
  carrier: string;
  estimatedDelivery: string;
  checkpoints: {
    title: string;
    location: string;
    time: string;
    completed: boolean;
  }[];
  paymentMethod: string;
  isOfflineSynced?: boolean;
}

export interface Address {
  fullName: string;
  street: string;
  city: string;
  state: string;
  zipCode: string;
  phone: string;
  isDefault?: boolean;
}

export interface UserProfile {
  id: string;
  name: string;
  email: string;
  avatar: string;
  role: 'customer' | 'seller' | 'admin';
  isPrimeMember: boolean;
  primeMemberSince?: string;
  walletBalance: number;
  savedAddresses: Address[];
  provider?: 'email' | 'google' | 'apple' | 'facebook' | 'github';
  twoFactorEnabled: boolean;
  createdAt: string;
}

export interface Review {
  id: string;
  author: string;
  avatar: string;
  rating: number;
  date: string;
  title: string;
  comment: string;
  verifiedPurchase: boolean;
  helpfulCount: number;
}

export interface BackupSnapshot {
  id: string;
  timestamp: string;
  version: string;
  recordCount: {
    orders: number;
    cart: number;
    wishlist: number;
    addresses: number;
  };
  hash: string;
  encryptedData: string;
  autoGenerated: boolean;
}

export interface SyncQueueItem {
  id: string;
  action: 'ADD_ORDER' | 'UPDATE_PROFILE' | 'ADD_ADDRESS' | 'CLEAR_CART';
  payload: any;
  timestamp: string;
  status: 'pending' | 'syncing' | 'completed' | 'failed';
  retryCount: number;
}

export interface SecurityAuditLog {
  id: string;
  event: string;
  timestamp: string;
  ipAddress: string;
  device: string;
  status: 'SUCCESS' | 'WARNING' | 'ALERT';
  signature: string;
}

export interface NotificationItem {
  id: string;
  title: string;
  message: string;
  timestamp: string;
  type: 'order' | 'deal' | 'security';
  read: boolean;
  linkTab?: 'store' | 'customer_hub' | 'seller_hub' | 'security_hub' | 'spring_boot_hub';
}

export interface ChatMessage {
  id: string;
  sender: 'user' | 'amazon_bot';
  text: string;
  timestamp: string;
  actionButtons?: { label: string; action: string }[];
}

export interface LightningDeal {
  id: string;
  productId: string;
  title: string;
  dealPrice: number;
  originalPrice: number;
  discountPct: number;
  claimedPct: number;
  endsInSeconds: number;
  image: string;
}

